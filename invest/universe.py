def write_starter(path=None) -> tuple[int, str]:
    """(Re)generate the starter universe CSV from the list above."""
    path = path or config.STARTER_UNIVERSE
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["ticker", "sector_hint", "source"])
        for tk, sector in STARTER_UNIVERSE:
            w.writerow([tk, sector, "curated starter list (invest/universe.py)"])
    return len(STARTER_UNIVERSE), str(path)


def write_full(path=None, refresh: bool = False, verbose: bool = True) -> tuple[int, str]:
    """Build the complete SEC-registered universe from company_tickers.json."""
    path = path or config.FULL_UNIVERSE
    path.parent.mkdir(parents=True, exist_ok=True)
    mapping = sec.load_ticker_map(refresh=refresh, verbose=verbose)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["ticker", "cik", "company_name", "source"])
        for tk in sorted(mapping):
            row = mapping[tk]
            w.writerow([tk, row["cik_padded"], row["name"],
                        "SEC company_tickers.json"])
    return len(mapping), str(path)


def load(path=None, limit: Optional[int] = None) -> list[dict]:
    """Read a universe CSV into a list of dicts."""
    path = path or config.STARTER_UNIVERSE
    if not path.exists():
        raise FileNotFoundError(
            "Universe file not found: " + str(path)
            + "\nBuild it first:  python scripts/build_universe.py"
        )
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return rows[:limit] if limit else rows


def sector_counts(rows: list[dict]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for r in rows:
        s = r.get("sector_hint") or "(unlabelled)"
        counts[s] = counts.get(s, 0) + 1
    return counts
